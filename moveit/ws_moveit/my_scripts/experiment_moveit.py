# ── MoveIt 2 Node ─────────────────────────────────────────────
class MoveItController(Node):
    def __init__(self):
        super().__init__("experiment_moveit")
        self._action_client = ActionClient(self, MoveGroup, "/move_action")
        self._tcp_pose = None

        self.create_subscription(
            PoseStamped,
            "/tcp_pose_broadcaster/pose",
            self._tcp_cb,
            10
        )

        self.get_logger().info("Waiting for MoveGroup action server...")
        self._action_client.wait_for_server()
        self.get_logger().info("MoveGroup action server ready.")

    def _tcp_cb(self, msg):
        self._tcp_pose = msg

    def get_tcp_z(self):
        self._tcp_pose = None

        # 5 second total wait
        deadline = time.time() + 5.0
        while self._tcp_pose is None and time.time() < deadline:
            rclpy.spin_once(self, timeout_sec=0.5)

        if self._tcp_pose is not None:
            z_mm = self._tcp_pose.pose.position.z * 1000.0
            self.get_logger().info(f"  TCP Z: {z_mm:.2f} mm")
            return z_mm
            
        self.get_logger().error("  TCP Z not available after 5s timeout")
        return None

    def get_tcp_z(self):
        rclpy.spin_once(self, timeout_sec=1.0)
        if self._tcp_pose is not None:
            z_mm = self._tcp_pose.pose.position.z * 1000.0
            self.get_logger().info(f"  TCP Z: {z_mm:.2f} mm")
            return z_mm
        return None

    def _build_request(self, x_m, y_m, z_m, max_velocity_scaling=SPEED_SCALE_PROBE):
        req = MotionPlanRequest()
        req.group_name = "ur_manipulator"
        req.num_planning_attempts = 5
        req.allowed_planning_time = 10.0
        req.max_velocity_scaling_factor = max_velocity_scaling
        req.max_acceleration_scaling_factor = ACCEL_SCALE

        target = PoseStamped()
        target.header.frame_id = "base"
        target.pose.position.x = x_m
        target.pose.position.y = y_m
        target.pose.position.z = z_m
        target.pose.orientation.x = ORI_QUAT[0]
        target.pose.orientation.y = ORI_QUAT[1]
        target.pose.orientation.z = ORI_QUAT[2]
        target.pose.orientation.w = ORI_QUAT[3]

        pos_con = PositionConstraint()
        pos_con.header.frame_id = "base"
        pos_con.link_name = "tool0"
        pos_con.target_point_offset = Vector3(x=0.0, y=0.0, z=0.0)
        bv = BoundingVolume()
        sp = SolidPrimitive()
        sp.type = SolidPrimitive.SPHERE
        sp.dimensions = [0.001]
        bv.primitives = [sp]
        bv.primitive_poses = [target.pose]
        pos_con.constraint_region = bv
        pos_con.weight = 1.0

        ori_con = OrientationConstraint()
        ori_con.header.frame_id = "base"
        ori_con.link_name = "tool0"
        ori_con.orientation = target.pose.orientation
        ori_con.absolute_x_axis_tolerance = 0.01
        ori_con.absolute_y_axis_tolerance = 0.01
        ori_con.absolute_z_axis_tolerance = 0.01
        ori_con.weight = 1.0

        goal_con = Constraints()
        goal_con.position_constraints = [pos_con]
        goal_con.orientation_constraints = [ori_con]
        req.goal_constraints = [goal_con]

        return req

    def move_to_mm(self, pos_mm, speed_scale=SPEED_SCALE_PROBE):
        """Move to position in mm with automatic retry on driver drop."""
        x_m, y_m, z_m = [p / 1000.0 for p in pos_mm]

        for attempt in range(1, MAX_RETRIES + 1):
            self.get_logger().info(
                f"  Moving to X={pos_mm[0]:.2f} Y={pos_mm[1]:.2f} Z={pos_mm[2]:.2f} mm"
                + (f" (attempt {attempt}/{MAX_RETRIES})" if attempt > 1 else "")
            )

            try:
                req = self._build_request(x_m, y_m, z_m, max_velocity_scaling=speed_scale)
                goal = MoveGroup.Goal()
                goal.request = req
                goal.planning_options.plan_only = False
                goal.planning_options.replan = True
                goal.planning_options.replan_attempts = 3

                future = self._action_client.send_goal_async(goal)
                rclpy.spin_until_future_complete(self, future, timeout_sec=15.0)

                if not future.done():
                    raise RuntimeError("Goal send timed out — driver likely dropped")

                goal_handle = future.result()
                if not goal_handle.accepted:
                    raise RuntimeError("Goal rejected — controller not running")

                result_future = goal_handle.get_result_async()
                rclpy.spin_until_future_complete(self, result_future, timeout_sec=30.0)

                if not result_future.done():
                    raise RuntimeError("Result timed out")

                result = result_future.result().result
                ec = result.error_code.val
                if ec != 1:
                    raise RuntimeError(f"Motion failed — error code: {ec}")

                return True

            except Exception as e:
                self.get_logger().error(f"  Move failed: {e}")
                if attempt < MAX_RETRIES:
                    self.get_logger().warn(
                        f"  Waiting {RETRY_WAIT_S}s for driver to restart before retry..."
                    )
                    time.sleep(RETRY_WAIT_S)
                    self._action_client = ActionClient(self, MoveGroup, "/move_action")
                    self.get_logger().info("  Waiting for MoveGroup action server...")
                    self._action_client.wait_for_server(timeout_sec=30.0)
                    self.get_logger().info("  Reconnected — retrying move...")
                else:
                    self.get_logger().error("  Max retries reached — giving up on this move")
                    return False

        return False

    def go_home(self):
        self.get_logger().info("Moving to home...")
        return self.move_to_mm(HOME_MM, speed_scale=SPEED_SCALE_TRANSIT)

# ── Live feed ─────────────────────────────────────────────────
def show_live_feed(duration=15):
    print("  Live feed — SPACE to continue, Q to skip height")
    start = time.time()
    while True:
        frames      = pipeline.wait_for_frames()
        color_frame = frames.get_color_frame()
        if not color_frame:
            continue
        img       = np.asanyarray(color_frame.get_data())
        results   = model(img, verbose=False)
        annotated, detections = draw_detections(img.copy(), results)
        n_det     = len(detections)
        elapsed   = time.time() - start
        cv2.putText(annotated,
                    f"Detections: {n_det}  |  {elapsed:.1f}s / {duration}s",
                    (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0, 255, 0), 2)
        cv2.putText(annotated,
                    "SPACE = continue  |  Q = skip height",
                    (10, 65), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0, 200, 255), 2)
        cv2.imshow("Live Detection", annotated)
        key = cv2.waitKey(1) & 0xFF
        if key == ord(' '):
            cv2.destroyAllWindows()
            return True
        elif key == ord('q'):
            cv2.destroyAllWindows()
            return False
        if elapsed > duration:
            cv2.destroyAllWindows()
            return True

# ── Tower detection ───────────────────────────────────────────
def flush_pipeline(n=10):
    for _ in range(n):
        pipeline.wait_for_frames()

def get_depth_at_pixel(depth_frame, cx, cy, window=5):
    depths = []
    for dx in range(-window, window + 1):
        for dy in range(-window, window + 1):
            px, py = cx + dx, cy + dy
            if 0 <= px < 1280 and 0 <= py < 720:
                d = depth_frame.get_distance(px, py)
                if d > 0:
                    depths.append(d)
    if len(depths) == 0:
        return 0
    return float(np.median(depths))

def draw_detections(frame, results):
    """Draw detections using same style as detect_towers.py."""
    detections = []
    for result in results:
        for box in result.boxes:
            conf = float(box.conf[0])
            if conf < CONFIDENCE_THRESHOLD:
                continue
            cls_id   = int(box.cls[0])
            cls_name = result.names[cls_id]
            x1, y1, x2, y2 = map(int, box.xyxy[0])
            colour = CLASS_COLOURS.get(cls_name, DEFAULT_COLOUR)
            cx_box = (x1 + x2) // 2
            cy_box = (y1 + y2) // 2

            if cls_name == "Center":
                cv2.line(frame, (cx_box - 20, cy_box), (cx_box + 20, cy_box), colour, 2)
                cv2.line(frame, (cx_box, cy_box - 20), (cx_box, cy_box + 20), colour, 2)
                cv2.circle(frame, (cx_box, cy_box), 5, colour, -1)
                cv2.rectangle(frame, (x1, y1), (x2, y2), colour, 1)
            else:
                cv2.rectangle(frame, (x1, y1), (x2, y2), colour, 2)

            label = f"{cls_name} {conf:.2f}"
            (lw, lh), _ = cv2.getTextSize(label, cv2.FONT_HERSHEY_SIMPLEX, 0.6, 2)
            cv2.rectangle(frame, (x1, y1 - lh - 8), (x1 + lw, y1), colour, -1)
            cv2.putText(frame, label, (x1, y1 - 4),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 0, 0), 2)

            detections.append({
                "class":  cls_name,
                "conf":   conf,
                "bbox":   (x1, y1, x2, y2),
                "centre": (cx_box, cy_box),
            })
    return frame, detections

def detect_towers(n_frames=10):
    flush_pipeline()
    detections = {k: [] for k in TOWERS}

    valid_frames = 0
    attempts     = 0
    MAX_ATTEMPTS = 50
    while valid_frames < n_frames and attempts < MAX_ATTEMPTS:
        attempts += 1

        frames      = pipeline.wait_for_frames()
        frames      = align.process(frames)
        color_frame = frames.get_color_frame()
        depth_frame = frames.get_depth_frame()
        if not color_frame or not depth_frame:
            continue
        img     = np.asanyarray(color_frame.get_data())
        results = model(img, verbose=False)[0]

        frame_data = {}
        for box in results.boxes:
            cls_name = model.names[int(box.cls)]
            if cls_name not in TOWERS:
                continue

            conf = float(box.conf[0])
            if conf < CONFIDENCE_THRESHOLD:
                continue

            cx = int((box.xyxy[0][0] + box.xyxy[0][2]) / 2)
            cy = int((box.xyxy[0][1] + box.xyxy[0][3]) / 2)
            z  = get_depth_at_pixel(depth_frame, cx, cy, window=5)
            if z == 0:
                continue

            # X, Y back-projection uses optical-centre Z (glass + 3.7mm).
            # Z is kept as glass-referenced for the coordinate transform,
            # where CAM_Z_OFFSET is also measured to the front glass.
            z_optical = z + CAM_GLASS_OFFSET
            x = (cx - intr.ppx) * z_optical / intr.fx
            y = (cy - intr.ppy) * z_optical / intr.fy
            frame_data[cls_name] = [x, y, z]

        if set(frame_data.keys()) == set(TOWERS):
            for cls_name, pt in frame_data.items():
                detections[cls_name].append(pt)
            valid_frames += 1
        else:
            missing = set(TOWERS) - set(frame_data.keys())
            print(f"    Frame {attempts} rejected — missing: {missing}")

    if valid_frames < n_frames:
        print(f"    ERROR: only {valid_frames} complete frames after {MAX_ATTEMPTS} attempts — skipping height")
        return {}

    result = {}
    for cls_name, pts in detections.items():
        result[cls_name] = np.median(pts, axis=0)
        print(f"    {cls_name} camera frame: "
            f"x={result[cls_name][0]:.4f} "
            f"y={result[cls_name][1]:.4f} "
            f"z={result[cls_name][2]:.4f} metres")

    return result

def camera_to_base(pt_cam, tcp_z_mm):
    """
    Camera 0,0 is directly above part 0,0.
    X, Y from camera frame with Y flipped.
    Z from depth reading corrected for camera height and extrusion offset.
    A tilt correction is applied to X: the aluminium camera bracket has a
    residual ~0.48deg tilt in -X, measured from multi-height vision tests.
    This causes X error proportional to depth, corrected by subtracting
    TILT_X_SLOPE * depth_mm from the back-projected X.
    """
    # X error due to camera tilt, dependent on Z
    depth_mm = pt_cam[2] * 1000

    base_x = PART_ORIGIN[0] + pt_cam[0] * 1000 - TILT_X_SLOPE * depth_mm + X_CONST_ERR
    base_y = PART_ORIGIN[1] + (-pt_cam[1]) * 1000 + Y_CONST_ERR
    camera_z_mm = tcp_z_mm - CAM_Z_OFFSET
    base_z = camera_z_mm - pt_cam[2] * 1000 + EXT_LENGTH + Z_CONST_ERR
    return np.array([base_x, base_y, base_z])

# ── Main ──────────────────────────────────────────────────────
def main():
    global pipeline, align, intr, model 

    # Camera setup
    pipeline = rs.pipeline()
    config = rs.config()
    config.enable_stream(rs.stream.color, 1280, 720, rs.format.bgr8, 5)
    config.enable_stream(rs.stream.depth, 1280, 720, rs.format.z16,  5)
    profile = pipeline.start(config)

    intr  = (profile.get_stream(rs.stream.color)
            .as_video_stream_profile().get_intrinsics())
    align = rs.align(rs.stream.color)

    # Flush 30 frames on startup — same as detect_towers.py
    print("[INFO] Flushing camera pipeline...")
    for _ in range(30):
        pipeline.wait_for_frames()
    print("[OK]  D405 streaming at 1280x720")

    # YOLO model
    print(f"[INFO] Loading model: {WEIGHTS}")
    model = YOLO(WEIGHTS)
    print(f"[OK]  Model loaded. Classes: {list(model.names.values())}")

    rclpy.init()
    robot = MoveItController()

    # Experiment loop
    print("\n" + "="*50)
    print(f"  EXPERIMENT — Platform: {PLATFORM}")
    print(f"  Log: {LOG_FILE}")
    print("="*50)

    print("\nMoving to home position...")
    robot.go_home()

    for height in TEST_HEIGHTS:

        # -20mm accounts for the offsets arising from
        # the tool extrusion
        test_z = HIGHEST_TOP_Z + height - 20

        print(f"\n{'='*50}")
        print(f"Height: {height}mm above highest tower  (Z={test_z:.2f}mm)")
        print(f"{'='*50}")

        # Move to observation position
        robot.move_to_mm([OBS_X, OBS_Y, test_z], speed_scale=SPEED_SCALE_TRANSIT)
        time.sleep(1.0)

        # Show live feed
        if not show_live_feed(duration=15):
            print(f"  Height {height}mm skipped")
            robot.go_home()
            continue

        # Get current TCP Z for depth calculation
        tcp_z_mm = robot.get_tcp_z()
        if tcp_z_mm is None:
            print(f"  ERROR: TCP Z not available — skipping height {height}mm")
            robot.go_home()
            continue

        print(f"  TCP Z: {tcp_z_mm:.2f}mm")

        # Detect towers
        print("  Detecting towers...")
        tower_positions = detect_towers(n_frames=10)

        if not tower_positions:
            print(f"  No towers detected at {height}mm — skipping")
            robot.go_home()
            continue

        print(f"  Detected: {list(tower_positions.keys())}")

        for tower_name, pt_cam in tower_positions.items():

            # Convert to base frame
            pt_base_mm = camera_to_base(pt_cam, tcp_z_mm)

            if np.any(np.isnan(pt_base_mm)):
                print(f"  WARNING: NaN for {tower_name} — skipping")
                continue

            # Deviation from known tower position
            known_pos = TOWER_KNOWN_POS[tower_name]
            dx = pt_base_mm[0] - known_pos[0]
            dy = pt_base_mm[1] - known_pos[1]
            dz = pt_base_mm[2] - known_pos[2]

            # Commanded probe — only relevant axis shifts
            cmd_x = np.array([KNOWN_PROBE_X[0] + dx, KNOWN_PROBE_X[1], KNOWN_PROBE_X[2]])
            cmd_y = np.array([KNOWN_PROBE_Y[0], KNOWN_PROBE_Y[1] + dy, KNOWN_PROBE_Y[2]])
            cmd_z = np.array([KNOWN_PROBE_Z[0], KNOWN_PROBE_Z[1], KNOWN_PROBE_Z[2] + dz])

            print(f"\n  Tower {tower_name}mm | detected: "
                  f"X={pt_base_mm[0]:.2f} Y={pt_base_mm[1]:.2f} "
                  f"Z={pt_base_mm[2]:.2f} mm")
            print(f"    Known:     X={known_pos[0]:.2f} Y={known_pos[1]:.2f} "
                  f"Z={known_pos[2]:.2f} mm")
            print(f"    Deviation: dX={dx:.2f} dY={dy:.2f} dZ={dz:.2f} mm")
            print(f"    CMD_X: X={cmd_x[0]:.2f} Y={cmd_x[1]:.2f} Z={cmd_x[2]:.2f}")
            print(f"    CMD_Y: X={cmd_y[0]:.2f} Y={cmd_y[1]:.2f} Z={cmd_y[2]:.2f}")
            print(f"    CMD_Z: X={cmd_z[0]:.2f} Y={cmd_z[1]:.2f} Z={cmd_z[2]:.2f}")

            # ── X axis ────────────────────────────────────────
            print("    → Approach XY")
            robot.move_to_mm(APPROACH_XY_MM, speed_scale=SPEED_SCALE_PROBE)
            print("    → Probe X zero position")
            robot.move_to_mm(PROBE_X_MM, speed_scale=SPEED_SCALE_PROBE)
            print("    → Offset X position")
            robot.move_to_mm([cmd_x[0], cmd_x[1], cmd_x[2]], speed_scale=SPEED_SCALE_PROBE)
            time.sleep(2.0)
            x_reading = float(input("    X dial gauge reading (mm): "))
            log_result(height, tower_name, "X", x_reading, pt_base_mm, cmd_x, dx)
            print("    → Back to approach XY")
            robot.move_to_mm(APPROACH_XY_MM, speed_scale=SPEED_SCALE_PROBE)

            # ── Y axis ────────────────────────────────────────
            print("    → Approach XY")
            robot.move_to_mm(APPROACH_XY_MM, speed_scale=SPEED_SCALE_PROBE)
            print("    → Probe Y zero position")
            robot.move_to_mm(PROBE_Y_MM, speed_scale=SPEED_SCALE_PROBE)
            print("    → Offset Y position")
            robot.move_to_mm([cmd_y[0], cmd_y[1], cmd_y[2]], speed_scale=SPEED_SCALE_PROBE)
            time.sleep(2.0)
            y_reading = -float(input("    Y dial gauge reading (mm): "))
            log_result(height, tower_name, "Y", y_reading, pt_base_mm, cmd_y, dy)
            print("    → Back to approach XY")
            robot.move_to_mm(APPROACH_XY_MM, speed_scale=SPEED_SCALE_PROBE)

            # ── Z axis ────────────────────────────────────────
            print("    → Safe Z intermediate")
            robot.move_to_mm(SAFE_Z_MM, speed_scale=SPEED_SCALE_PROBE)
            print("    → Approach Z")
